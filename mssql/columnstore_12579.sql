-- MSSQL enterprise temporal system-versioned store 12579
CREATE SCHEMA IF NOT EXISTS cs_12579;
GO
CREATE TABLE cs_12579.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12579.summarize_12579 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12579.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
