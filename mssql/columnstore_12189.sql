-- MSSQL enterprise temporal system-versioned store 12189
CREATE SCHEMA IF NOT EXISTS cs_12189;
GO
CREATE TABLE cs_12189.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12189.summarize_12189 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12189.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
