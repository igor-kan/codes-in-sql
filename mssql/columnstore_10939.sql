-- MSSQL enterprise temporal system-versioned store 10939
CREATE SCHEMA IF NOT EXISTS cs_10939;
GO
CREATE TABLE cs_10939.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10939.summarize_10939 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10939.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
