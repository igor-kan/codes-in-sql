-- MSSQL enterprise temporal system-versioned store 13109
CREATE SCHEMA IF NOT EXISTS cs_13109;
GO
CREATE TABLE cs_13109.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_13109.summarize_13109 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_13109.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
