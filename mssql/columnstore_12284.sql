-- MSSQL enterprise temporal system-versioned store 12284
CREATE SCHEMA IF NOT EXISTS cs_12284;
GO
CREATE TABLE cs_12284.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12284.summarize_12284 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12284.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
