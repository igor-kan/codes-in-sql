-- MSSQL enterprise temporal system-versioned store 10249
CREATE SCHEMA IF NOT EXISTS cs_10249;
GO
CREATE TABLE cs_10249.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10249.summarize_10249 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10249.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
