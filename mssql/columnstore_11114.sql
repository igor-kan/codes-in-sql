-- MSSQL enterprise temporal system-versioned store 11114
CREATE SCHEMA IF NOT EXISTS cs_11114;
GO
CREATE TABLE cs_11114.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_11114.summarize_11114 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_11114.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
