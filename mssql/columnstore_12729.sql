-- MSSQL enterprise temporal system-versioned store 12729
CREATE SCHEMA IF NOT EXISTS cs_12729;
GO
CREATE TABLE cs_12729.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12729.summarize_12729 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12729.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
