-- MSSQL enterprise temporal system-versioned store 11134
CREATE SCHEMA IF NOT EXISTS cs_11134;
GO
CREATE TABLE cs_11134.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_11134.summarize_11134 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_11134.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
