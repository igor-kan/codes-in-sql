-- MSSQL enterprise temporal system-versioned store 12714
CREATE SCHEMA IF NOT EXISTS cs_12714;
GO
CREATE TABLE cs_12714.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12714.summarize_12714 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12714.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
