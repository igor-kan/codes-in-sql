-- MSSQL enterprise temporal system-versioned store 12309
CREATE SCHEMA IF NOT EXISTS cs_12309;
GO
CREATE TABLE cs_12309.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12309.summarize_12309 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12309.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
