-- MSSQL enterprise temporal system-versioned store 11509
CREATE SCHEMA IF NOT EXISTS cs_11509;
GO
CREATE TABLE cs_11509.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_11509.summarize_11509 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_11509.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
