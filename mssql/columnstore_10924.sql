-- MSSQL enterprise temporal system-versioned store 10924
CREATE SCHEMA IF NOT EXISTS cs_10924;
GO
CREATE TABLE cs_10924.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10924.summarize_10924 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10924.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
