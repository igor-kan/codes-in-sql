-- MSSQL enterprise temporal system-versioned store 10629
CREATE SCHEMA IF NOT EXISTS cs_10629;
GO
CREATE TABLE cs_10629.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10629.summarize_10629 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10629.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
