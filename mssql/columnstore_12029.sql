-- MSSQL enterprise temporal system-versioned store 12029
CREATE SCHEMA IF NOT EXISTS cs_12029;
GO
CREATE TABLE cs_12029.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12029.summarize_12029 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12029.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
