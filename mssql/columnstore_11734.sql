-- MSSQL enterprise temporal system-versioned store 11734
CREATE SCHEMA IF NOT EXISTS cs_11734;
GO
CREATE TABLE cs_11734.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_11734.summarize_11734 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_11734.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
