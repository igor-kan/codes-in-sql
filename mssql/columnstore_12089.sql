-- MSSQL enterprise temporal system-versioned store 12089
CREATE SCHEMA IF NOT EXISTS cs_12089;
GO
CREATE TABLE cs_12089.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12089.summarize_12089 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12089.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
