-- MSSQL enterprise temporal system-versioned store 12084
CREATE SCHEMA IF NOT EXISTS cs_12084;
GO
CREATE TABLE cs_12084.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12084.summarize_12084 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12084.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
