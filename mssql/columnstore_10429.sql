-- MSSQL enterprise temporal system-versioned store 10429
CREATE SCHEMA IF NOT EXISTS cs_10429;
GO
CREATE TABLE cs_10429.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10429.summarize_10429 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10429.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
