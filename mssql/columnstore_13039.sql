-- MSSQL enterprise temporal system-versioned store 13039
CREATE SCHEMA IF NOT EXISTS cs_13039;
GO
CREATE TABLE cs_13039.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_13039.summarize_13039 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_13039.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
