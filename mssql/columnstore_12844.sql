-- MSSQL enterprise temporal system-versioned store 12844
CREATE SCHEMA IF NOT EXISTS cs_12844;
GO
CREATE TABLE cs_12844.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12844.summarize_12844 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12844.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
