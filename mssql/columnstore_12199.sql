-- MSSQL enterprise temporal system-versioned store 12199
CREATE SCHEMA IF NOT EXISTS cs_12199;
GO
CREATE TABLE cs_12199.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12199.summarize_12199 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12199.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
