-- MSSQL enterprise temporal system-versioned store 11719
CREATE SCHEMA IF NOT EXISTS cs_11719;
GO
CREATE TABLE cs_11719.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_11719.summarize_11719 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_11719.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
