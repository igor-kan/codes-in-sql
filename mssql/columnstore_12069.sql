-- MSSQL enterprise temporal system-versioned store 12069
CREATE SCHEMA IF NOT EXISTS cs_12069;
GO
CREATE TABLE cs_12069.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12069.summarize_12069 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12069.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
