-- MSSQL enterprise temporal system-versioned store 10724
CREATE SCHEMA IF NOT EXISTS cs_10724;
GO
CREATE TABLE cs_10724.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10724.summarize_10724 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10724.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
