-- MSSQL enterprise temporal system-versioned store 10464
CREATE SCHEMA IF NOT EXISTS cs_10464;
GO
CREATE TABLE cs_10464.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_10464.summarize_10464 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_10464.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
