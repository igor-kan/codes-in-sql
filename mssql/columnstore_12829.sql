-- MSSQL enterprise temporal system-versioned store 12829
CREATE SCHEMA IF NOT EXISTS cs_12829;
GO
CREATE TABLE cs_12829.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_12829.summarize_12829 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_12829.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
