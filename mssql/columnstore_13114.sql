-- MSSQL enterprise temporal system-versioned store 13114
CREATE SCHEMA IF NOT EXISTS cs_13114;
GO
CREATE TABLE cs_13114.signals (
  id BIGINT IDENTITY(1,1), uid UNIQUEIDENTIFIER DEFAULT NEWID(),
  val FLOAT NOT NULL, ts DATETIME2(7) DEFAULT SYSUTCDATETIME(),
  INDEX cci CLUSTERED COLUMNSTORE
);
GO
CREATE PROCEDURE cs_13114.summarize_13114 AS BEGIN SET NOCOUNT ON;
  SELECT DATETRUNC(hour,ts) h, AVG(val) avg_val, COUNT(*) cnt
  FROM cs_13114.signals GROUP BY DATETRUNC(hour,ts);
END;
GO
