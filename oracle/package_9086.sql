CREATE OR REPLACE PACKAGE pkg_9086 AS
  FUNCTION calc_9086(p_base NUMBER, p_rate NUMBER, p_n INT) RETURN NUMBER;
END pkg_9086;
/
CREATE OR REPLACE PACKAGE BODY pkg_9086 AS
  FUNCTION calc_9086(p_base NUMBER, p_rate NUMBER, p_n INT) RETURN NUMBER IS
    v NUMBER:=p_base;
